// Standalone assert check (no JS unit-test runner in this repo). Run with:
//   bun src/styles/hardcodedColours.test.ts
//
// DanyWhere: the user's theme file (theme_file.rs) restyles the app through
// the tokens of theme.css. A colour written straight into a component can't
// be reached that way, so every colour lives in a token file, and the few
// that can't are listed below with the reason. A Tailwind palette class
// (text-white, bg-black/50, border-red-500) counts as one too: it bypasses
// the app's tokens.
import assert from "node:assert/strict";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";

const SRC = new URL("..", import.meta.url).pathname;

/** Generated from Rust, whose doc comments cite issues as #1234. */
const GENERATED = new Set(["bindings.ts"]);

/** Files that hold the tokens themselves. */
const TOKEN_FILES = new Set([
  "styles/theme.css",
  // Kept apart from theme.css so upstream merges never touch it.
  "styles/danywhere-wordmark.css",
]);

interface Allowed {
  file: string;
  /** The colour as written. */
  colour: string;
  /** Only on lines that match this. */
  line?: RegExp;
  why: string;
}

const ALLOWED: Allowed[] = [
  {
    file: "components/SecureInputWarning.tsx",
    colour: "#1578",
    why: "an issue number in a comment, not a colour",
  },
  {
    file: "components/settings/debug/KeyboardDiagnostic.tsx",
    colour: "#1578",
    why: "an issue number in a comment, not a colour",
  },
  ...["#3C9CAA", "#225F73", "#ffffff"].map((colour) => ({
    file: "components/icons/DanyWhereWordmark.tsx",
    colour,
    why:
      "the app icon's tile and pin, drawn as the icon is (the icon itself" +
      " can't be themed); generated by the sidecar's to_component.py",
  })),
  ...["#7C3AED", "#FFFFFF", "#F28C28", "#1A1A1A", "#6B7280", "#8B5CF6"].map(
    (colour) => ({
      file: "lib/variant.ts",
      colour,
      why:
        "a test build's mark, the hue of its tray dot, which is baked into" +
        " the tray PNGs; not part of the scheme",
    }),
  ),
  ...[
    "overlay/RecordingOverlay.css",
    "components/onboarding/screens/tryit.css",
  ].map((file) => ({
    file,
    colour: "#000",
    line: /mask-image/,
    why: "an alpha mask: only its opacity counts, never its colour",
  })),
];

// A function name may follow an underscore, as in Tailwind's
// shadow-[0_8px_rgba(0,0,0,0.4)].
const COLOUR =
  /(?<![\w&])#[0-9a-fA-F]{3,8}\b|(?<![A-Za-z])(?:rgba?|hsla?|oklch|oklab|lch|lab)\(/g;
const PALETTE_CLASS =
  /\b(?:bg|text|border|fill|stroke|ring|from|to|via|shadow|outline|decoration|divide|accent|caret|placeholder)-(?:white|black|slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose)(?:-\d{2,3})?(?:\/\d+)?\b/g;

const sources = (dir: string): string[] =>
  readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return sources(path);
    if (name.endsWith(".test.ts")) return [];
    return /\.(tsx?|css|html)$/.test(name) ? [path] : [];
  });

interface Found {
  file: string;
  line: number;
  colour: string;
  text: string;
}

const found: Found[] = [];
for (const path of sources(SRC)) {
  const file = relative(SRC, path);
  if (TOKEN_FILES.has(file) || GENERATED.has(file)) continue;
  const lines = readFileSync(path, "utf8").split("\n");
  lines.forEach((text, index) => {
    const patterns = file.endsWith(".css") ? [COLOUR] : [COLOUR, PALETTE_CLASS];
    for (const pattern of patterns) {
      for (const match of text.matchAll(pattern)) {
        found.push({ file, line: index + 1, colour: match[0], text });
      }
    }
  });
}

const allowedBy = (hit: Found) =>
  ALLOWED.find(
    (a) =>
      a.file === hit.file &&
      a.colour === hit.colour &&
      (!a.line || a.line.test(hit.text)),
  );

const unlisted = found.filter((hit) => !allowedBy(hit));
const unused = ALLOWED.filter(
  (a) => !found.some((hit) => allowedBy(hit) === a),
);

let failures = 0;
try {
  assert.deepEqual(
    unlisted.map((h) => `${h.file}:${h.line} ${h.colour}`),
    [],
    `${unlisted.length} colours outside the token files; move them into a` +
      " token in src/styles/theme.css, or list them in ALLOWED with the reason",
  );
} catch (error) {
  failures += 1;
  console.error(`FAILED: ${(error as Error).message}`);
}
try {
  assert.deepEqual(
    unused.map((a) => `${a.file} ${a.colour}`),
    [],
    "ALLOWED lists colours that are gone; remove them",
  );
} catch (error) {
  failures += 1;
  console.error(`FAILED: ${(error as Error).message}`);
}

if (failures > 0) {
  console.error(
    `hardcodedColours: ${failures} of 2 checks failed (${unlisted.length} unlisted colours)`,
  );
  process.exit(1);
}
console.log(
  `hardcodedColours: all 2 checks passed (${found.length} allowed colours in ${ALLOWED.length} entries)`,
);
