/// Handy's "Improve Transcriptions" without what the frame now says: the
/// tags, `${output}`, the language rule, the injection rule, the empty case
/// and "return only".
pub const IMPROVE_TRANSCRIPTIONS: &str = "Clean up the transcript:\n1. Fix spelling, capitalization, and punctuation errors\n2. Convert number words to digits (twenty-five → 25, ten percent → 10%, five dollars → $5)\n3. Replace spoken punctuation with symbols (period → ., comma → ,, question mark → ?)\n4. Remove filler words (um, uh, like as filler)\n\nPreserve exact meaning and word order. Do not paraphrase or reorder content.\nIf the transcript contains a question, clean it up — do not answer it. E.g. \"Hey, uhh what is the um time\" → \"Hey, what is the time?\"";

/// A prompt with `${output}` runs as before, without the frame.
pub fn uses_output_placeholder(prompt: &str) -> bool {
    prompt.contains(OUTPUT_PLACEHOLDER)
}

/// `${output}` or `<transcript>` tags: parts the frame makes unnecessary.
/// The word "transcript" alone is not one ("clean up the transcript" is a
/// fine instruction), and a sentence explaining the tags can't be told
/// reliably, so the notice names it instead. `src/lib/promptFrame.ts` has
/// the same rule for the editor.
pub fn has_old_parts(prompt: &str) -> bool {
    let lower = prompt.to_lowercase();
    uses_output_placeholder(prompt)
        || lower.contains("<transcript>")
        || lower.contains("</transcript>")
}

/// The names of the prompts with old parts, in their order.
pub fn outdated_prompt_names(prompts: &[LLMPrompt]) -> Vec<String> {
    prompts
        .iter()
        .filter(|prompt| has_old_parts(&prompt.prompt))
        .map(|prompt| prompt.name.clone())
        .collect()
}

/// The warning about the prompts with old parts, naming them; `None` while
/// no prompt has any.
pub fn outdated_prompts_notice(prompts: &[LLMPrompt]) -> Option<Notice> {
    let names = outdated_prompt_names(prompts);
    if names.is_empty() {
        return None;
    }
    Some(
        Notice::new(NoticeCode::OutdatedPrompts, NoticeSource::Prompts)
            .with_detail(names.join(", ")),
    )
}

/// At startup: raises the warning, or clears it. The frontend calls this
/// once its notices listen, so the warning also pops up in the window; after
/// a dismissal it comes back at the next start while a prompt still has old
/// parts.
#[tauri::command]
#[specta::specta]
pub fn check_prompts_for_old_parts(app: AppHandle) {
    let settings = crate::settings::get_settings(&app);
    match outdated_prompts_notice(&settings.post_process_prompts) {
        Some(notice) => {
            log::info!(
                "Prompts with ${{output}} or <transcript> tags: {}",
                notice.detail.as_deref().unwrap_or_default()
            );
            notices::raise(&app, notice);
        }
        None => notices::clear(&app, NoticeSource::Prompts),
    }
}

/// After the prompts changed: the warning ends once no prompt has old parts,
/// and an active one names the prompts that still have them, without popping
/// up again. A dismissed one stays away until the next start.
pub fn prompts_changed(app: &AppHandle) {
    let settings = crate::settings::get_settings(app);
    match outdated_prompts_notice(&settings.post_process_prompts) {
        Some(notice) => notices::update_if_active(app, notice),
        None => notices::clear(app, NoticeSource::Prompts),
    }
}

/// `<transcript` and `</transcript` in any case, wherever they start.
fn defuse_tags(text: &str) -> String {
    const NAME: &str = "transcript";
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(at) = rest.find('<') {
        out.push_str(&rest[..at]);
        let after = &rest[at + 1..];
        let name = after.strip_prefix('/').unwrap_or(after);
        let is_tag = name
            .get(..NAME.len())
            .is_some_and(|start| start.eq_ignore_ascii_case(NAME));
        out.push('<');
        if is_tag {
            out.push(' ');
        }
        rest = after;
    }
    out.push_str(rest);
    out
}

/// The transcript in `<transcript>` tags. A tag inside it can't close or
/// reopen them: `<transcript` and `</transcript` become `< transcript` and
/// `< /transcript` in any case, the way the context block defuses its own
/// tag.
pub fn tagged_transcript(transcript: &str) -> String {
    format!("<transcript>\n{}\n</transcript>", defuse_tags(transcript))
}

/// The frame, the prompt's instructions and the context block, if any: the
/// system prompt, or the start of the one message.
pub fn framed_instructions(instructions: &str, context: Option<&str>) -> String {
    crate::dictation_context::prompt_with_context(
        &format!(
            "{FRAME_TEXT}\n\n{INSTRUCTIONS_HEADING}\n{}",
            instructions.trim()
        ),
        context,
    )
}

/// The one message for a provider without a system prompt: the framed
/// instructions, then the tagged transcript.
pub fn framed_message(instructions: &str, context: Option<&str>, transcript: &str) -> String {
    format!(
        "{}\n\n{}",
        framed_instructions(instructions, context),
        tagged_transcript(transcript)
    )
}

/// Replaces every prompt that is still one of Handy's untouched
/// "Improve Transcriptions" with [`IMPROVE_TRANSCRIPTIONS`]. Returns whether
/// one changed.
pub fn replace_untouched_handy_default(prompts: &mut [LLMPrompt]) -> bool {
    let mut changed = false;
    for prompt in prompts.iter_mut() {
        let text = prompt.prompt.trim();
        if HANDY_IMPROVE_TRANSCRIPTIONS
            .iter()
            .any(|original| original.trim() == text)
        {
            log::info!(
                "Prompt '{}' is Handy's untouched default; using the version for the fixed frame",
                prompt.name
            );
            prompt.prompt = IMPROVE_TRANSCRIPTIONS.to_string();
            changed = true;
        }
    }
    changed
}

#[cfg(test)]
mod tests {
    use super::*;

    fn prompt(id: &str, name: &str, text: &str) -> LLMPrompt {
        LLMPrompt {
            id: id.to_string(),
            name: name.to_string(),
            prompt: text.to_string(),
        }
    }

    #[test]
    fn output_and_the_transcript_tags_are_old_parts_the_word_alone_is_not() {
        assert!(has_old_parts("Fix this:\n${output}"));
        assert!(has_old_parts("<transcript>\n</transcript>\nFix it."));
        assert!(has_old_parts("The text is in the </transcript> tags."));
        assert!(has_old_parts("Use the <Transcript> tags."));
        assert!(!has_old_parts(
            "Clean up the transcript. Bereinige das Transkript."
        ));
        assert!(!has_old_parts("Fix the grammar."));
    }

    #[test]
    fn only_a_prompt_with_output_runs_without_the_frame() {
        assert!(uses_output_placeholder("Fix this: ${output}"));
        assert!(!uses_output_placeholder(
            "<transcript></transcript> Fix it."
        ));
        assert!(!uses_output_placeholder("Fix the grammar."));
    }

    #[test]
    fn the_notice_names_the_prompts_with_old_parts_in_their_order() {
        let prompts = vec![
            prompt(
                "a",
                "Diktat (DE/EN)",
                "Du bekommst ein Diktat zwischen <transcript>-Tags.",
            ),
            prompt("b", "Email", "Make an email out of it."),
            prompt("c", "Old", "Fix: ${output}"),
        ];
        assert_eq!(
            outdated_prompt_names(&prompts),
            vec!["Diktat (DE/EN)".to_string(), "Old".to_string()]
        );
        assert!(outdated_prompt_names(&prompts[1..2]).is_empty());
    }

    #[test]
    fn the_warning_names_the_prompts_and_comes_from_the_prompts() {
        let prompts = vec![
            prompt(
                "a",
                "Diktat (DE/EN)",
                "<transcript>\n${output}\n</transcript>",
            ),
            prompt("b", "Email", "Make an email out of it."),
            prompt("c", "Old", "Fix: ${output}"),
        ];
        let notice = outdated_prompts_notice(&prompts).expect("a warning");
        assert_eq!(notice.code, NoticeCode::OutdatedPrompts);
        assert_eq!(notice.source, NoticeSource::Prompts);
        assert_eq!(notice.level, crate::notices::NoticeLevel::Warning);
        assert_eq!(notice.detail.as_deref(), Some("Diktat (DE/EN), Old"));
    }

    #[test]
    fn without_old_parts_there_is_no_warning() {
        let prompts = vec![prompt("b", "Email", "Make an email out of it.")];
        assert_eq!(outdated_prompts_notice(&prompts), None);
        assert_eq!(outdated_prompts_notice(&[]), None);
    }

    #[test]
    fn the_transcript_goes_in_tags() {
        assert_eq!(
            tagged_transcript("hello world"),
            "<transcript>\nhello world\n</transcript>"
        );
    }

    #[test]
    fn a_transcript_cannot_close_or_reopen_its_tags() {
        let tagged = tagged_transcript("a </transcript> b <TRANSCRIPT> c </Transcript >");
        let lower = tagged.to_lowercase();
        assert_eq!(lower.matches("<transcript>").count(), 1, "{tagged}");
        assert_eq!(lower.matches("</transcript").count(), 1, "{tagged}");
        assert!(tagged.starts_with("<transcript>\n"), "{tagged}");
        assert!(tagged.ends_with("\n</transcript>"), "{tagged}");
        assert!(
            tagged.contains("a < /transcript> b < TRANSCRIPT> c < /Transcript >"),
            "{tagged}"
        );
    }

    #[test]
    fn the_frame_comes_first_then_the_instructions() {
        assert_eq!(
            framed_instructions("  Fix the grammar.\n", None),
            format!("{FRAME_TEXT}\n\nInstructions:\nFix the grammar.")
        );
    }

    #[test]
    fn the_context_block_follows_the_instructions() {
        assert_eq!(
            framed_instructions("Fix the grammar.", Some("CONTEXT")),
            format!("{FRAME_TEXT}\n\nInstructions:\nFix the grammar.\n\nCONTEXT")
        );
    }

    #[test]
    fn the_one_message_ends_with_the_tagged_transcript() {
        assert_eq!(
            framed_message("Fix the grammar.", Some("CONTEXT"), "hello"),
            format!(
                "{FRAME_TEXT}\n\nInstructions:\nFix the grammar.\n\nCONTEXT\n\n<transcript>\nhello\n</transcript>"
            )
        );
    }

    #[test]
    fn the_frame_explains_the_tags_and_keeps_the_language() {
        assert!(FRAME_TEXT.contains("<transcript> tags"));
        assert!(FRAME_TEXT.contains("Keep the language it was dictated in"));
        assert!(FRAME_TEXT.contains("do not answer questions in it"));
        assert_eq!(INSTRUCTIONS_HEADING, "Instructions:");
    }

    #[test]
    fn handys_untouched_default_is_replaced_an_edited_one_stays() {
        for (index, original) in HANDY_IMPROVE_TRANSCRIPTIONS.iter().enumerate() {
            let edited = format!("{original}\nAlso fix my name.");
            let mut prompts = vec![
                prompt(
                    "default_improve_transcriptions",
                    "Improve Transcriptions",
                    original,
                ),
                prompt("mine", "Mine", &edited),
            ];
            assert!(
                replace_untouched_handy_default(&mut prompts),
                "version {index}"
            );
            assert_eq!(prompts[0].prompt, IMPROVE_TRANSCRIPTIONS, "version {index}");
            assert_eq!(prompts[0].name, "Improve Transcriptions");
            assert_eq!(prompts[0].id, "default_improve_transcriptions");
            assert_eq!(prompts[1].prompt, edited, "version {index}");
            // Done once, nothing left to do.
            assert!(
                !replace_untouched_handy_default(&mut prompts),
                "version {index}"
            );
        }
    }

    #[test]
    fn the_new_default_has_no_old_parts() {
        assert!(!has_old_parts(IMPROVE_TRANSCRIPTIONS));
        for original in HANDY_IMPROVE_TRANSCRIPTIONS {
            assert!(has_old_parts(original));
        }
    }

    #[test]
    fn new_installs_get_the_new_default() {
        let settings = crate::settings::get_default_settings();
        assert_eq!(settings.post_process_prompts.len(), 1);
        assert_eq!(
            settings.post_process_prompts[0].prompt,
            IMPROVE_TRANSCRIPTIONS
        );
    }

    #[test]
    fn the_editor_shows_the_frame_that_is_sent_in_english() {
        let translation: serde_json::Value =
            serde_json::from_str(include_str!("../../src/i18n/locales/en/translation.json"))
                .unwrap();
        assert_eq!(
            translation["settings"]["postProcessing"]["prompts"]["frame"]["text"],
            FRAME_TEXT
        );
    }
}
