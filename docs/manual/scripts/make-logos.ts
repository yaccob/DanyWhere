// Generates the manual's logo files from the app's wordmark component, so the
// manual shows exactly the mark the app shows:
//   src/assets/wordmark-light.svg, src/assets/wordmark-dark.svg  (site title)
//   public/favicon.svg                                           (icon tile)
// The colours the component takes from CSS variables are filled in from
// src/styles/danywhere-wordmark.css, one file per theme.
//
// Run: bun docs/manual/scripts/make-logos.ts

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const manualDir = join(import.meta.dir, "..");
const repoDir = join(manualDir, "..", "..");
const componentPath = join(
  repoDir,
  "src/components/icons/DanyWhereWordmark.tsx",
);
const coloursPath = join(repoDir, "src/styles/danywhere-wordmark.css");

const component = readFileSync(componentPath, "utf8");
const colours = readFileSync(coloursPath, "utf8");

function colour(theme: "light" | "dark", name: string): string {
  const match = colours.match(
    new RegExp(`--${theme}-color-wordmark-${name}:\\s*(#[0-9a-fA-F]{3,8})`),
  );
  if (!match)
    throw new Error(`no ${theme} colour for ${name} in ${coloursPath}`);
  return match[1];
}

const svgMatch = component.match(/<svg[\s\S]*?<\/svg>/);
if (!svgMatch) throw new Error(`no <svg> in ${componentPath}`);
const jsx = svgMatch[0];

const viewBox = jsx.match(/viewBox="([^"]+)"/)?.[1];
const defs = jsx.match(/<defs>[\s\S]*?<\/defs>/)?.[0];
const body = jsx.match(/<g aria-hidden="true">([\s\S]*?)<\/g>/)?.[1];
if (!viewBox || !defs || !body) {
  throw new Error(`unexpected structure in ${componentPath}`);
}

/** Turns the component's JSX into plain SVG markup for one theme. */
function toSvg(markup: string, theme: "light" | "dark"): string {
  return markup
    .replace(/id=\{tileGradient\}/g, 'id="tile"')
    .replace(/id=\{anyGradient\}/g, 'id="any"')
    .replace(/\{`url\(#\$\{tileGradient\}\)`\}/g, '"url(#tile)"')
    .replace(/\{`url\(#\$\{anyGradient\}\)`\}/g, '"url(#any)"')
    .replace(
      /style=\{\{\s*stopColor:\s*"var\(--color-wordmark-any-(top|bottom)\)"\s*\}\}/g,
      (_, end: string) => `stop-color="${colour(theme, `any-${end}`)}"`,
    )
    .replace(/"var\(--color-wordmark-where\)"/g, `"${colour(theme, "where")}"`)
    .replace(
      /\b(stopColor|strokeWidth|strokeLinejoin|strokeLinecap|fillRule)=/g,
      (_, name: string) =>
        `${name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}=`,
    )
    .replace(/\n\s*/g, " ")
    .replace(/\s+\/>/g, "/>")
    .replace(/>\s+</g, "><")
    .trim();
}

function checkPlain(svg: string, file: string): string {
  if (/[{}]|var\(/.test(svg)) {
    throw new Error(
      `JSX or CSS variables left in ${file}: ${svg.match(/.{0,40}[{}].{0,40}|.{0,40}var\(.{0,40}/)?.[0]}`,
    );
  }
  return svg;
}

const header =
  "<!-- Generated by docs/manual/scripts/make-logos.ts from src/components/icons/DanyWhereWordmark.tsx; regenerate rather than edit. -->";

for (const theme of ["light", "dark"] as const) {
  const file = join(manualDir, "src/assets", `wordmark-${theme}.svg`);
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" width="426" height="161" role="img" aria-label="DanyWhere">` +
    toSvg(defs, theme) +
    `<g>${toSvg(body, theme)}</g></svg>`;
  writeFileSync(file, `${header}\n${checkPlain(svg, file)}\n`);
  console.log(`wrote ${file}`);
}

// The favicon is the icon tile alone: the rect and the four white shapes
// before the first letter, which is the first path filled with a gradient.
const tileEnd = body.indexOf("fill={`url(#${anyGradient})`}");
const tileBody = body.slice(0, body.lastIndexOf("<path", tileEnd));
const tileDefs = defs.replace(
  /<linearGradient\s+id=\{anyGradient\}[\s\S]*?<\/linearGradient>/,
  "",
);
const faviconFile = join(manualDir, "public", "favicon.svg");
const favicon =
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 -152.75 157.13 157.13">` +
  toSvg(tileDefs, "light") +
  toSvg(tileBody, "light") +
  `</svg>`;
writeFileSync(faviconFile, `${header}\n${checkPlain(favicon, faviconFile)}\n`);
console.log(`wrote ${faviconFile}`);
